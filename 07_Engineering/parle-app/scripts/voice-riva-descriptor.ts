// Writes api/_voice/riva-descriptor.ts from the NVIDIA Riva protos (nvidia-riva/common, riva/proto/), so the relay
// loads them without reading files at run time. Run: bun scripts/voice-riva-descriptor.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import protobuf from "protobufjs";

const base = fileURLToPath(new URL("./voice-proto/", import.meta.url));
const root = new protobuf.Root();
root.resolvePath = (_origin: string, target: string) => base + target;
root.loadSync(["riva/proto/riva_tts.proto", "riva/proto/riva_asr.proto"], { keepCase: true });
const out = fileURLToPath(new URL("../api/_voice/riva-descriptor.ts", import.meta.url));
writeFileSync(out, `// GENERATED by scripts/voice-riva-descriptor.ts from scripts/voice-proto (NVIDIA Riva protos). Do not edit.\nexport const RIVA_DESCRIPTOR: Record<string, unknown> = ${JSON.stringify(root.toJSON())};\n`);
console.log("wrote api/_voice/riva-descriptor.ts");
