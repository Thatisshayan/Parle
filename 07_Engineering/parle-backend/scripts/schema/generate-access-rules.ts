import { readFileSync, writeFileSync } from "node:fs";
import { ENTITY_DIR } from "../spikes/readability";

export type Tier =
  | { tier: "owner_read" }
  | { tier: "participant_read"; participantColumns: string[] }
  | { tier: "public_read"; condition: string; hiddenColumns: string[] }
  | { tier: "server_only" };

/** `columns` (all columns of the table) is required for public_read: anon may only see the non-hidden ones. */
export function accessSql(table: string, t: Tier, columns: string[] = []): string {
  const q = `public."${table}"`;
  const lines = [`alter table ${q} enable row level security;`, `revoke all on ${q} from anon, authenticated;`];
  if (t.tier === "owner_read") {
    lines.push(`grant select on ${q} to authenticated;`, `create policy "${table}: owner reads" on ${q} for select to authenticated using (owner_id = auth.uid());`);
  } else if (t.tier === "participant_read") {
    const cond = ["owner_id = auth.uid()", ...t.participantColumns.map((c) => `"${c}" = auth.uid()::text`)].join(" or ");
    lines.push(`grant select on ${q} to authenticated;`, `create policy "${table}: participants read" on ${q} for select to authenticated using (${cond});`);
  } else if (t.tier === "public_read") {
    const visible = columns.filter((c) => !t.hiddenColumns.includes(c));
    if (!visible.length) throw new Error(`public_read on ${table} needs its column list`);
    lines.push(
      `grant select (${visible.map((c) => `"${c}"`).join(", ")}) on ${q} to anon, authenticated;`,
      `create policy "${table}: public reads" on ${q} for select to anon, authenticated using (${t.condition});`,
    );
  }
  return lines.join("\n");
}

if (import.meta.main) {
  const map: Record<string, Tier> = JSON.parse(readFileSync(`${import.meta.dir}/../../schema/access-tiers.json`, "utf8"));
  const columnsOf = (t: string) => ["id", "created_at", "updated_at", "created_by", "owner_id", ...Object.keys(JSON.parse(readFileSync(`${ENTITY_DIR}/${t}.json`, "utf8")).properties)];
  const body = Object.keys(map).sort().map((t) => accessSql(t, map[t], columnsOf(t))).join("\n\n");
  writeFileSync(`${import.meta.dir}/../../supabase/migrations/20261014000004_access_rules.sql`,
    `-- Generated by scripts/schema/generate-access-rules.ts from schema/access-tiers.json. Do not edit by hand.\n-- Browser roles never write app tables; Edge Functions write with the service role (spec section 4).\n-- Public tables grant selected columns only: no emails, owner ids or tutor user ids (review finding 1).\n\n${body}\n`);
  console.log("wrote 20261014000004_access_rules.sql");
}
